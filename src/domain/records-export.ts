import { sortTables } from './ddl';
import { DIALECTS, findType, isSerial, quoteIdent, quoteLiteral } from './dialects';
import { validateValue } from './records';
import type { Column, DataRow, DialectId, Project, Schema, Table } from './types';

/** Rows per INSERT statement. Oracle (before 23ai) takes a single row per VALUES clause. */
const CHUNK = 100;

const NUMERIC = /^[+-]?(\d+(\.\d*)?|\.\d+)([eE][+-]?\d+)?$/;
const NON_ASCII = /[^\x00-\x7f]/;
const TEXT_GENERICS = new Set(['char', 'varchar', 'nchar', 'nvarchar', 'text', 'ntext', 'enum']);

const supportsDefaultKeyword = (dialect: DialectId) => dialect === 'postgresql' || dialect === 'mysql' || dialect === 'sqlserver';

const isGenerated = (dialect: DialectId, column: Column) => column.autoIncrement || isSerial(dialect, column.type);

/** A value written as a SQL literal for the column type, in the syntax of each gestor. */
export const sqlLiteral = (dialect: DialectId, column: Column, raw: string): string => {
  const value = raw.trim();
  if (!value) return 'NULL';
  const def = findType(DIALECTS[dialect], column.type);
  const generic = def?.generic;
  if ((def?.integer || def?.serial || generic === 'decimal' || generic === 'real' || generic === 'double' || generic === 'money') && NUMERIC.test(value)) {
    return value;
  }
  if (generic === 'bool') {
    const truthy = ['true', '1'].includes(value.toLowerCase());
    const falsy = ['false', '0'].includes(value.toLowerCase());
    if (truthy || falsy) return dialect === 'sqlserver' ? (truthy ? '1' : '0') : truthy ? 'TRUE' : 'FALSE';
  }
  if (dialect === 'oracle') {
    if (generic === 'date') return `DATE ${quoteLiteral(value)}`;
    if (generic === 'datetime' || generic === 'timestamptz') return `TIMESTAMP ${quoteLiteral(value.replace('T', ' '))}`;
    if (generic === 'uuid') return `HEXTORAW(${quoteLiteral(value.replace(/-/g, '').toUpperCase())})`;
  }
  if (dialect === 'sqlserver' && generic && TEXT_GENERICS.has(generic) && NON_ASCII.test(value)) return `N${quoteLiteral(raw)}`;
  return quoteLiteral(raw);
};

/** Statement that switches to the project's database, so a data-only script lands in the right place. */
const useDatabase = (dialect: DialectId, databaseName?: string) => {
  const name = databaseName?.trim();
  if (!name) return null;
  const q = quoteIdent(dialect, name);
  if (dialect === 'postgresql') return `\\connect ${q}`;
  if (dialect === 'mysql') return `USE ${q};`;
  if (dialect === 'sqlserver') return `USE ${q};\nGO`;
  if (dialect === 'oracle') return `ALTER SESSION SET CURRENT_SCHEMA = ${q};`;
  return null;
};

/** Statements that move identity sequences past the inserted keys, so new rows do not collide. */
const resyncSequences = (dialect: DialectId, table: Table, columns: Column[]) => {
  const t = quoteIdent(dialect, table.name);
  return columns
    .filter((c) => isGenerated(dialect, c))
    .flatMap((column) => {
      const c = quoteIdent(dialect, column.name);
      if (dialect === 'postgresql') {
        return [`SELECT setval(pg_get_serial_sequence(${quoteLiteral(t)}, ${quoteLiteral(column.name)}), COALESCE(MAX(${c}), 1)) FROM ${t};`];
      }
      if (dialect === 'oracle') return [`ALTER TABLE ${t} MODIFY ${c} GENERATED BY DEFAULT AS IDENTITY (START WITH LIMIT VALUE);`];
      return [];
    });
};

export type InsertResult = { sql: string; rowCount: number; invalidCells: number };

const tableInserts = (dialect: DialectId, table: Table, rows: DataRow[], counter: { invalid: number }) => {
  // Columns no row fills are left out, so the database applies its defaults and identities.
  const columns = table.columns.filter((c) => rows.some((r) => (r.values[c.id] ?? '').trim()));
  if (columns.length === 0) return null;
  const t = quoteIdent(dialect, table.name);
  const columnList = columns.map((c) => quoteIdent(dialect, c.name)).join(', ');
  const tuple = (row: DataRow) =>
    `(${columns
      .map((column) => {
        const raw = row.values[column.id] ?? '';
        if (raw.trim() && validateValue(dialect, column, raw.trim())) counter.invalid += 1;
        if (!raw.trim() && supportsDefaultKeyword(dialect) && (isGenerated(dialect, column) || column.defaultValue?.trim())) return 'DEFAULT';
        return sqlLiteral(dialect, column, raw);
      })
      .join(', ')})`;

  const size = dialect === 'oracle' ? 1 : CHUNK;
  const statements: string[] = [];
  for (let i = 0; i < rows.length; i += size) {
    const chunk = rows.slice(i, i + size).map(tuple);
    statements.push(`INSERT INTO ${t} (${columnList}) VALUES\n  ${chunk.join(',\n  ')};`);
  }
  const identity = dialect === 'sqlserver' && columns.some((c) => c.autoIncrement);
  return [
    `-- ${table.name}: ${rows.length} ${rows.length === 1 ? 'registro' : 'registros'}`,
    ...(identity ? [`SET IDENTITY_INSERT ${t} ON;`] : []),
    ...statements,
    ...(identity ? [`SET IDENTITY_INSERT ${t} OFF;`] : []),
    ...resyncSequences(dialect, table, columns),
  ].join('\n');
};

/**
 * INSERT statements for every row, with referenced tables first so foreign keys resolve.
 * `standalone` adds the header and the statement that switches to the database.
 */
export const generateInserts = (project: Project, schema: Schema, standalone = true): InsertResult => {
  const { dialect } = project;
  const records = project.records ?? {};
  const counter = { invalid: 0 };
  const blocks: string[] = [];
  let rowCount = 0;

  if (standalone) {
    blocks.push(`-- Registros de ${project.name || 'Proyecto'}\n-- Gestor: ${DIALECTS[dialect].name}`);
    const use = useDatabase(dialect, project.databaseName);
    if (use) blocks.push(use);
    if (dialect === 'sqlite') blocks.push('PRAGMA foreign_keys = ON;');
  }
  for (const table of sortTables(schema.tables)) {
    const rows = records[table.id] ?? [];
    if (rows.length === 0) continue;
    const block = tableInserts(dialect, table, rows, counter);
    if (!block) continue;
    blocks.push(block);
    rowCount += rows.length;
  }
  if (rowCount === 0) blocks.push('-- No hay registros.');
  return { sql: `${blocks.join('\n\n')}\n`, rowCount, invalidCells: counter.invalid };
};

/* CSV */

const csvField = (value: string) => (/[",\r\n]/.test(value) || /^\s|\s$/.test(value) ? `"${value.replace(/"/g, '""')}"` : value);

/** RFC 4180 CSV with a header row. Blank cells stay empty. */
export const tableToCsv = (table: Table, rows: DataRow[]) =>
  [table.columns.map((c) => csvField(c.name)), ...rows.map((r) => table.columns.map((c) => csvField(r.values[c.id] ?? '')))]
    .map((line) => line.join(','))
    .join('\r\n') + '\r\n';

/* JSON */

/** JSON value for a cell: numbers and booleans become native when the value is valid for the type. */
export const jsonValue = (dialect: DialectId, column: Column, raw: string): string | number | boolean | null => {
  const value = raw.trim();
  if (!value) return null;
  if (validateValue(dialect, column, value)) return raw;
  const def = findType(DIALECTS[dialect], column.type);
  if (def?.integer || def?.serial) {
    const n = Number(value);
    return Number.isSafeInteger(n) ? n : value;
  }
  switch (def?.generic) {
    case 'decimal':
    case 'real':
    case 'double':
    case 'money':
      return Number(value);
    case 'bool':
      return ['true', '1'].includes(value.toLowerCase());
    default:
      return raw;
  }
};

/** Every table's rows keyed by table name, each row keyed by column name. */
export const recordsToJson = (project: Project, schema: Schema) => {
  const records = project.records ?? {};
  const data = Object.fromEntries(
    schema.tables.map((table) => [
      table.name,
      (records[table.id] ?? []).map((row) =>
        Object.fromEntries(table.columns.map((c) => [c.name, jsonValue(project.dialect, c, row.values[c.id] ?? '')])),
      ),
    ]),
  );
  return `${JSON.stringify(data, null, 2)}\n`;
};
