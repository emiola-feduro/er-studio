import { describe, expect, it } from 'vitest';
import { generateDdl } from '../ddl';
import { buildSchema } from '../inference';
import { importIr } from '.';
import type { Ir } from './ir';
import oracle from './fixtures/oracle-schema.json';

/** What the desktop side reads from Oracle 23ai Free (the assertions of crates/er-db/tests/engines.rs). */
describe('a schema read from Oracle', () => {
  const read = oracle as unknown as { ir: Ir };
  const { project, report } = importIr(structuredClone(read.ir), 'sql', { name: 'tienda', dialect: 'oracle', namesLocale: 'es' });
  const entity = (name: string) => project.entities.find((e) => e.name === name)!;
  const attribute = (table: string, name: string) => entity(table).attributes.find((a) => a.name === name)!;

  it('keeps the Oracle types, the identity, the enum and the cascade', () => {
    expect(project.entities.map((e) => e.name).sort()).toEqual(['CLIENTE', 'PEDIDO']);
    expect(attribute('CLIENTE', 'ID')).toMatchObject({ pk: true, autoIncrement: true });
    expect(attribute('CLIENTE', 'NOMBRE')).toMatchObject({ type: 'VARCHAR2', length: 80 });
    expect(attribute('CLIENTE', 'SALDO')).toMatchObject({ type: 'NUMBER', precision: 10, scale: 2 });
    expect(attribute('CLIENTE', 'CREADO')).toMatchObject({ type: 'TIMESTAMP' });
    expect(attribute('CLIENTE', 'FOTO')).toMatchObject({ type: 'BLOB' });
    expect(attribute('CLIENTE', 'NOTAS')).toMatchObject({ type: 'CLOB' });
    expect(attribute('CLIENTE', 'TIPO')).toMatchObject({ type: 'ENUM', enumValues: ['persona', 'empresa'] });
    expect(project.relationships).toHaveLength(1);
    expect(project.relationships[0].onDelete).toBe('CASCADE');
    expect(report.warnings).toContain('skipped:VIEW V_CLIENTE');
  });

  it('gives back Oracle DDL', () => {
    const ddl = generateDdl(buildSchema(project), 'oracle').sql;
    expect(ddl).toMatch(/GENERATED BY DEFAULT AS IDENTITY/);
    expect(ddl).toMatch(/VARCHAR2\(80\)/);
    expect(ddl).toMatch(/ON DELETE CASCADE/);
    expect(ddl).toMatch(/IDX_PEDIDO_TOTAL/);
  });
});
