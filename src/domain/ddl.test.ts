import { describe, expect, it } from 'vitest';
import { generateDdl } from './ddl';
import { convertType, formatType } from './dialects';
import { makeProject } from './fixtures';
import { buildSchema } from './inference';
import { changeDialect } from './model';
import type { DialectId } from './types';

const shop = (dialect: DialectId) => {
  const b = makeProject(dialect);
  const cliente = b.entity('cliente', ['nombre']);
  const pedido = b.entity('pedido');
  const rel = b.relate([cliente, pedido], '1:N');
  rel.onDelete = 'CASCADE';
  pedido.indexes.push({
    id: 'i',
    name: '',
    nameIsCustom: false,
    unique: false,
    method: dialect === 'postgresql' ? 'btree' : undefined,
    where: 'id > 0',
    columns: [{ columnId: pedido.attributes[0].id, order: 'DESC' }],
  });
  return b.project;
};

const ddl = (dialect: DialectId) => {
  const project = shop(dialect);
  return generateDdl(buildSchema(project), dialect, { projectName: project.name });
};

describe('generateDdl', () => {
  it('PostgreSQL: identity, ALTER TABLE FKs, index with USING and WHERE', () => {
    const { sql, warnings } = ddl('postgresql');
    expect(sql).toContain('id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    expect(sql).toContain('nombre VARCHAR(255)');
    expect(sql).toContain('CONSTRAINT pk_cliente PRIMARY KEY (id)');
    expect(sql).toContain(
      'ALTER TABLE pedido\n  ADD CONSTRAINT fk_pedido_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id) ON DELETE CASCADE;',
    );
    expect(sql).toContain('CREATE INDEX idx_pedido_id ON pedido USING btree (id DESC) WHERE id > 0;');
    expect(sql.indexOf('CREATE TABLE cliente')).toBeLessThan(sql.indexOf('CREATE TABLE pedido'));
    expect(warnings).toEqual([]);
  });

  it('MySQL: AUTO_INCREMENT and a warning for partial indexes', () => {
    const { sql, warnings } = ddl('mysql');
    expect(sql).toContain('id INT NOT NULL AUTO_INCREMENT');
    expect(sql).not.toContain('WHERE');
    expect(warnings.some((w) => w.includes('parciales'))).toBe(true);
  });

  it('SQLite: inline INTEGER PRIMARY KEY AUTOINCREMENT and inline FKs', () => {
    const { sql } = ddl('sqlite');
    expect(sql).toContain('PRAGMA foreign_keys = ON;');
    expect(sql).toContain('id INTEGER PRIMARY KEY AUTOINCREMENT');
    expect(sql).not.toContain('ALTER TABLE');
    expect(sql).toContain('CONSTRAINT fk_pedido_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (id) ON DELETE CASCADE');
  });

  it('SQL Server: IDENTITY(1,1)', () => {
    expect(ddl('sqlserver').sql).toContain('id INT IDENTITY(1,1) NOT NULL');
  });

  it('Oracle: identity and no ON UPDATE', () => {
    const project = shop('oracle');
    project.relationships[0].onUpdate = 'CASCADE';
    const { sql, warnings } = generateDdl(buildSchema(project), 'oracle');
    expect(sql).toContain('id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL');
    expect(sql).not.toContain('ON UPDATE');
    expect(warnings.some((w) => w.includes('ON UPDATE'))).toBe(true);
  });

  it('quotes reserved words with the dialect quote', () => {
    const b = makeProject('mysql');
    b.entity('order');
    expect(generateDdl(buildSchema(b.project), 'mysql').sql).toContain('CREATE TABLE `order`');
    const s = makeProject('sqlserver');
    s.entity('user');
    expect(generateDdl(buildSchema(s.project), 'sqlserver').sql).toContain('CREATE TABLE [user]');
  });

  it('junction composite PK in DDL', () => {
    const b = makeProject('postgresql');
    b.relate([b.entity('alumno'), b.entity('curso')], 'N:M');
    const { sql } = generateDdl(buildSchema(b.project), 'postgresql');
    expect(sql).toContain('CONSTRAINT pk_alumno_curso PRIMARY KEY (alumno_id, curso_id)');
    expect(sql).toContain('alumno_id INTEGER NOT NULL');
  });
});

describe('dialect conversion', () => {
  it('formats types with params', () => {
    expect(formatType('postgresql', { type: 'NUMERIC', precision: 12, scale: 3 })).toBe('NUMERIC(12,3)');
    expect(formatType('postgresql', { type: 'VARCHAR' })).toBe('VARCHAR(255)');
    expect(formatType('postgresql', { type: 'TEXT', length: 9 })).toBe('TEXT');
  });

  it('maps through generic categories', () => {
    expect(convertType('postgresql', 'mysql', { type: 'UUID' })).toEqual({ type: 'CHAR', length: 36 });
    expect(convertType('postgresql', 'oracle', { type: 'VARCHAR', length: 80 })).toEqual({ type: 'VARCHAR2', length: 80 });
    expect(convertType('mysql', 'sqlserver', { type: 'BOOLEAN' })).toEqual({ type: 'BIT' });
    expect(convertType('postgresql', 'oracle', { type: 'BOOLEAN' })).toEqual({ type: 'NUMBER', precision: 1, scale: 0 });
    expect(convertType('postgresql', 'mysql', { type: 'MI_TIPO' })).toBeNull();
  });

  it('changeDialect converts every attribute and reports custom types', () => {
    const b = makeProject('postgresql');
    const e = b.entity('e', ['a']);
    e.attributes.push({ ...e.attributes[1], id: 'x', name: 'raro', type: 'GEOGRAPHY' });
    const report = changeDialect(b.project, 'sqlserver');
    expect(b.project.dialect).toBe('sqlserver');
    expect(e.attributes.map((a) => a.type)).toEqual(['INT', 'VARCHAR', 'GEOGRAPHY']);
    expect(report.kept).toEqual(['e.raro (GEOGRAPHY)']);
  });
});
