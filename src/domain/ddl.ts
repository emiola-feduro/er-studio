import { ddlType, DIALECTS, isAutoIncrementable, isEnum, isSerial, quoteIdent, quoteLiteral } from './dialects';
import type { Column, DialectId, ForeignKey, Schema, Table, TableIndex } from './types';

export type DdlResult = { sql: string; warnings: string[] };

/** Orders tables so referenced tables come before the tables that reference them. */
export const sortTables = (tables: Table[]): Table[] => {
  const byId = new Map(tables.map((t) => [t.id, t]));
  const visited = new Set<string>();
  const result: Table[] = [];
  const visit = (table: Table, stack: Set<string>) => {
    if (visited.has(table.id) || stack.has(table.id)) return;
    stack.add(table.id);
    for (const fk of table.foreignKeys) {
      const ref = byId.get(fk.refTableId);
      if (ref && ref.id !== table.id) visit(ref, stack);
    }
    stack.delete(table.id);
    visited.add(table.id);
    result.push(table);
  };
  for (const table of tables) visit(table, new Set());
  return result;
};

const columnList = (dialect: DialectId, table: Table, ids: string[]) =>
  ids.map((id) => quoteIdent(dialect, table.columns.find((c) => c.id === id)?.name ?? id)).join(', ');

const actionClause = (dialect: DialectId, fk: ForeignKey, warnings: string[]) => {
  const parts: string[] = [];
  if (fk.onDelete !== 'NO ACTION') parts.push(`ON DELETE ${fk.onDelete}`);
  if (fk.onUpdate !== 'NO ACTION') {
    if (DIALECTS[dialect].supportsOnUpdate) parts.push(`ON UPDATE ${fk.onUpdate}`);
    else warnings.push(`${DIALECTS[dialect].name} no soporta ON UPDATE; se omitió en "${fk.name}".`);
  }
  return parts.length ? ` ${parts.join(' ')}` : '';
};

const fkClause = (dialect: DialectId, fk: ForeignKey, tables: Map<string, Table>, warnings: string[]) => {
  const holder = tables.get(fk.tableId)!;
  const ref = tables.get(fk.refTableId)!;
  return (
    `CONSTRAINT ${quoteIdent(dialect, fk.name)} FOREIGN KEY (${columnList(dialect, holder, fk.columnIds)}) ` +
    `REFERENCES ${quoteIdent(dialect, ref.name)} (${columnList(dialect, ref, fk.refColumnIds)})` +
    actionClause(dialect, fk, warnings)
  );
};

type ColumnContext = { dialect: DialectId; table: Table; inlinePk: boolean; warnings: string[] };

const columnDefinition = (col: Column, ctx: ColumnContext) => {
  const { dialect, table, inlinePk, warnings } = ctx;
  const parts = [quoteIdent(dialect, col.name), ddlType(dialect, col)];
  const auto = col.autoIncrement && !isSerial(dialect, col.type);

  if (auto && !isAutoIncrementable(dialect, col.type)) {
    warnings.push(`"${table.name}.${col.name}" es autoincremental pero ${col.type} no es un tipo entero; se omitió.`);
  } else if (auto) {
    if (dialect === 'postgresql' || dialect === 'oracle') parts.push('GENERATED BY DEFAULT AS IDENTITY');
    if (dialect === 'sqlserver') parts.push('IDENTITY(1,1)');
  }
  if (inlinePk) parts.push('PRIMARY KEY AUTOINCREMENT');
  if (col.defaultValue?.trim()) parts.push(`DEFAULT ${col.defaultValue.trim()}`);
  if (!col.nullable && !inlinePk) parts.push('NOT NULL');
  if (auto && dialect === 'mysql' && isAutoIncrementable(dialect, col.type)) parts.push('AUTO_INCREMENT');
  if (auto && dialect === 'sqlite' && !inlinePk) {
    warnings.push(
      `SQLite solo permite AUTOINCREMENT en una PK INTEGER de una sola columna; se omitió en "${table.name}.${col.name}".`,
    );
  }
  if (col.check?.trim()) parts.push(`CHECK (${col.check.trim()})`);
  return parts.join(' ');
};

const createTable = (table: Table, dialect: DialectId, tables: Map<string, Table>, warnings: string[]) => {
  const pkCols = table.pk?.columnIds ?? [];
  const singlePk = pkCols.length === 1 ? table.columns.find((c) => c.id === pkCols[0]) : undefined;
  const inlinePkId =
    dialect === 'sqlite' && singlePk?.autoIncrement && singlePk.type.toUpperCase() === 'INTEGER' ? singlePk.id : undefined;

  const lines = table.columns.map((col) =>
    columnDefinition(col, { dialect, table, inlinePk: col.id === inlinePkId, warnings }),
  );
  if (table.pk && !inlinePkId) {
    lines.push(`CONSTRAINT ${quoteIdent(dialect, table.pk.name)} PRIMARY KEY (${columnList(dialect, table, table.pk.columnIds)})`);
  }
  for (const col of table.columns) {
    if (col.unique && !col.pk) {
      lines.push(`CONSTRAINT ${quoteIdent(dialect, `uq_${table.name}_${col.name}`)} UNIQUE (${quoteIdent(dialect, col.name)})`);
    }
  }
  for (const col of table.columns) {
    if (isEnum(col.type) && col.enumValues?.length) {
      const allowed = col.enumValues.map(quoteLiteral).join(', ');
      lines.push(`CONSTRAINT ${quoteIdent(dialect, `ck_${table.name}_${col.name}`)} CHECK (${quoteIdent(dialect, col.name)} IN (${allowed}))`);
    }
  }
  for (const uq of table.uniques) {
    lines.push(`CONSTRAINT ${quoteIdent(dialect, uq.name)} UNIQUE (${columnList(dialect, table, uq.columnIds)})`);
  }
  if (!DIALECTS[dialect].supportsAlterAddFk) {
    for (const fk of table.foreignKeys) lines.push(fkClause(dialect, fk, tables, warnings));
  }
  if (lines.length === 0) {
    warnings.push(`"${table.name}" no tiene columnas.`);
  }
  return `CREATE TABLE ${quoteIdent(dialect, table.name)} (\n  ${lines.join(',\n  ')}\n);`;
};

const createIndex = (table: Table, index: TableIndex, dialect: DialectId, warnings: string[]) => {
  const d = DIALECTS[dialect];
  if (index.columns.length === 0) {
    warnings.push(`El índice "${index.name}" no tiene columnas; se omitió.`);
    return null;
  }
  const cols = index.columns
    .map((ic) => {
      const name = quoteIdent(dialect, table.columns.find((c) => c.id === ic.columnId)?.name ?? ic.columnId);
      return ic.order === 'DESC' ? `${name} DESC` : name;
    })
    .join(', ');
  const method = index.method && d.indexMethods.includes(index.method) ? index.method : undefined;
  const name = quoteIdent(dialect, index.name);
  const tableName = quoteIdent(dialect, table.name);
  let unique = index.unique ? 'UNIQUE ' : '';
  let sql: string;

  switch (dialect) {
    case 'postgresql':
      sql = `CREATE ${unique}INDEX ${name} ON ${tableName}${method ? ` USING ${method}` : ''} (${cols})`;
      break;
    case 'mysql':
      sql = `CREATE ${unique}INDEX ${name} ON ${tableName} (${cols})${method ? ` USING ${method}` : ''}`;
      break;
    case 'sqlserver':
      sql = `CREATE ${unique}${method ? `${method} ` : ''}INDEX ${name} ON ${tableName} (${cols})`;
      break;
    case 'oracle':
      if (method === 'BITMAP' && unique) {
        warnings.push(`Oracle no permite índices BITMAP únicos; "${index.name}" se generó como BITMAP no único.`);
        unique = '';
      }
      sql = `CREATE ${unique}${method ? `${method} ` : ''}INDEX ${name} ON ${tableName} (${cols})`;
      break;
    default:
      sql = `CREATE ${unique}INDEX ${name} ON ${tableName} (${cols})`;
  }
  if (index.where?.trim()) {
    if (d.supportsPartialIndex) sql += ` WHERE ${index.where.trim()}`;
    else warnings.push(`${d.name} no soporta índices parciales; se omitió el WHERE de "${index.name}".`);
  }
  return `${sql};`;
};

/** Statements that create the database and make it the current one, in each gestor's own syntax. */
export const databaseStatements = (dialect: DialectId, databaseName: string, warnings: string[] = []): string | null => {
  const name = databaseName.trim();
  if (!name) return null;
  const q = quoteIdent(dialect, name);
  switch (dialect) {
    case 'postgresql':
      return `CREATE DATABASE ${q};\n\\connect ${q}`;
    case 'mysql':
      return `CREATE DATABASE IF NOT EXISTS ${q};\nUSE ${q};`;
    case 'sqlserver':
      return `CREATE DATABASE ${q};\nGO\nUSE ${q};\nGO`;
    case 'oracle':
      warnings.push('En Oracle la base de datos se crea con herramientas de administración; el script solo cambia al esquema indicado.');
      return `ALTER SESSION SET CURRENT_SCHEMA = ${q};`;
    case 'sqlite':
      warnings.push(`En SQLite la base de datos es el archivo; abre o crea "${name}.db" antes de ejecutar el script.`);
      return `-- Base de datos: ${name}.db`;
  }
};

export type DdlOptions = { projectName?: string; databaseName?: string };

export const generateDdl = (schema: Schema, dialect: DialectId, options: DdlOptions = {}): DdlResult => {
  const { projectName = '', databaseName = '' } = options;
  const warnings: string[] = [];
  const tables = sortTables(schema.tables);
  const byId = new Map(schema.tables.map((t) => [t.id, t]));
  const blocks: string[] = [];

  blocks.push(`-- ${projectName || 'Proyecto'}\n-- Gestor: ${DIALECTS[dialect].name}`);
  const database = databaseStatements(dialect, databaseName, warnings);
  if (database) blocks.push(database);
  if (dialect === 'sqlite') blocks.push('PRAGMA foreign_keys = ON;');

  for (const table of tables) blocks.push(createTable(table, dialect, byId, warnings));

  if (DIALECTS[dialect].supportsAlterAddFk) {
    const fkLines = tables.flatMap((table) =>
      table.foreignKeys.map(
        (fk) => `ALTER TABLE ${quoteIdent(dialect, table.name)}\n  ADD ${fkClause(dialect, fk, byId, warnings)};`,
      ),
    );
    if (fkLines.length) blocks.push(fkLines.join('\n\n'));
  }

  const indexLines = tables.flatMap((table) =>
    table.indexes.map((index) => createIndex(table, index, dialect, warnings)).filter((s): s is string => Boolean(s)),
  );
  if (indexLines.length) blocks.push(indexLines.join('\n'));

  return { sql: `${blocks.join('\n\n')}\n`, warnings };
};
